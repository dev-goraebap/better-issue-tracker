package io.github.goraebap.bit.shared.config;

import java.io.IOException;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.Objects;
import java.util.Properties;
import org.springframework.boot.EnvironmentPostProcessor;
import org.springframework.boot.SpringApplication;
import org.springframework.core.Ordered;
import org.springframework.core.env.ConfigurableEnvironment;
import org.springframework.core.env.PropertiesPropertySource;

/** Keeps generated secrets beside the database; explicit configuration always wins. */
public class GeneratedSecrets implements EnvironmentPostProcessor, Ordered {
    private static final SecureRandom RANDOM = new SecureRandom();
    private static final String[] KEYS = {"app.auth.secret", "app.git.encryption-key"};

    @Override
    public void postProcessEnvironment(ConfigurableEnvironment environment, SpringApplication application) {
        if (!environment.getProperty("app.secrets.generate", Boolean.class, true)) return;
        Path file = Path.of(environment.getProperty("DB_PATH", "./data/bit.db"))
                .toAbsolutePath()
                .resolveSibling("secrets.properties");
        Properties kept = read(file);
        Properties used = new Properties();
        boolean changed = false;
        for (String key : KEYS) {
            String configured = environment.getProperty(key);
            if (configured != null && !configured.isBlank()) continue;
            if (kept.getProperty(key, "").isBlank()) {
                byte[] bytes = new byte[32];
                RANDOM.nextBytes(bytes);
                kept.setProperty(key, Base64.getEncoder().encodeToString(bytes));
                changed = true;
            }
            used.setProperty(key, kept.getProperty(key));
        }
        if (changed) write(file, kept);
        environment.getPropertySources().addFirst(new PropertiesPropertySource("generatedSecrets", used));
    }

    @Override
    public int getOrder() {
        return Ordered.LOWEST_PRECEDENCE;
    }

    private static Properties read(Path file) {
        Properties properties = new Properties();
        if (!Files.isRegularFile(file)) return properties;
        try (Reader reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
            properties.load(reader);
            return properties;
        } catch (IOException exception) {
            throw new UncheckedIOException(exception);
        }
    }

    private static void write(Path file, Properties properties) {
        try {
            Files.createDirectories(Objects.requireNonNull(file.getParent()));
            // Set restrictive permissions before writing secret bytes on POSIX systems.
            if (!Files.exists(file)) {
                try {
                    Files.createFile(
                            file, PosixFilePermissions.asFileAttribute(PosixFilePermissions.fromString("rw-------")));
                } catch (UnsupportedOperationException windows) {
                    Files.createFile(file);
                }
            }
            try (Writer writer = Files.newBufferedWriter(file, StandardCharsets.UTF_8)) {
                properties.store(writer, "Generated by BIT; back up with the database. Never commit.");
            }
        } catch (IOException exception) {
            throw new UncheckedIOException(exception);
        }
    }
}
